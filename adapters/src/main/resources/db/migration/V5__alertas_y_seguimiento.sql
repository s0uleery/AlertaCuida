-- Alertas, atención del equipo, avisos a contactos y al reloj, y seguimiento de casos (tarea 1.1.5).

-- Lo que pasó y lo que hizo el reloj: la evidencia del evento. La escriben solo el reloj
-- (o el servidor, si la alerta es suya). Después solo se completan las fechas que el reloj informa
-- más tarde (agravamiento, cancelación, sin respuesta), controlado con permisos de la base.
-- El estado no se guarda: lo calcula la vista alerta_estado.
-- Una sola alerta del servidor abierta por reloj y tipo (2.2.5): la valida el job al crearla, con
-- pg_advisory_xact_lock(hashtextextended(id_asignacion::text || ':' || tipo_evento, 0)).
-- Lo valida el backend: una alerta cancelada no tiene atención ni avisos a contactos.
CREATE TABLE alerta (
	id_alerta uuid PRIMARY KEY DEFAULT gen_random_uuid(),
	numero bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL,  -- folio legible (#142)
	event_id uuid NOT NULL UNIQUE,              -- lo genera el reloj, o el servidor si la alerta es suya
	id_asignacion uuid NOT NULL REFERENCES asignacion_reloj (id_asignacion) ON DELETE CASCADE,
	hash_configuracion varchar,                 -- configuración que usó el reloj; vacío si es del servidor
	origen varchar NOT NULL CHECK (origen IN ('RELOJ', 'SERVIDOR')),
	tipo_evento varchar NOT NULL CHECK (tipo_evento IN ('CAIDA', 'FC', 'SPO2', 'FC_SPO2', 'TENDENCIA',
		'INACTIVIDAD', 'SILENCIO_DATOS', 'BATERIA_BAJA', 'RELOJ_NO_PUESTO')),
	-- Gravedad con que llegó; la actual es GRAVE si se agravó
	severidad varchar NOT NULL CHECK (severidad IN ('LEVE', 'MEDIA', 'GRAVE')),
	fecha_hora_agravamiento timestamptz,        -- caída leve o media que sube a grave por inmovilidad (2.1.3)
	evidencia jsonb,                            -- lecturas, niveles, umbrales, versión y celda de la matriz
	es_simulacro boolean NOT NULL DEFAULT false,
	espera_dia_habil boolean NOT NULL DEFAULT false,  -- leve fuera del horario hábil: el reloj no avisa
	fecha_hora_deteccion timestamptz,
	fecha_hora_envio timestamptz,               -- fin de la ventana de 30 s
	fecha_hora_recepcion timestamptz NOT NULL,
	fecha_hora_cancelacion timestamptz,         -- el paciente la canceló en los 30 s (1.4.4)
	fecha_hora_sin_respuesta timestamptz,       -- el reloj terminó la lista dos veces sin confirmación
	CONSTRAINT alerta_cancelada CHECK (fecha_hora_cancelacion IS NULL OR fecha_hora_sin_respuesta IS NULL),
	CONSTRAINT alerta_origen CHECK ((origen = 'SERVIDOR') = (hash_configuracion IS NULL)),
	CONSTRAINT alerta_agravamiento CHECK (fecha_hora_agravamiento IS NULL
		OR (tipo_evento = 'CAIDA' AND severidad <> 'GRAVE')),
	-- Solo la leve espera; media y grave avisan siempre
	CONSTRAINT alerta_espera_leve CHECK (NOT espera_dia_habil OR severidad = 'LEVE'),
	-- El servidor solo crea técnicas y simulacros
	CONSTRAINT alerta_servidor_tecnica CHECK (origen = 'RELOJ' OR es_simulacro
		OR tipo_evento IN ('SILENCIO_DATOS', 'BATERIA_BAJA', 'RELOJ_NO_PUESTO')),
	-- El silencio de datos solo lo detecta el servidor
	CONSTRAINT alerta_silencio_servidor CHECK (tipo_evento <> 'SILENCIO_DATOS' OR origen = 'SERVIDOR')
);

CREATE INDEX alerta_asignacion ON alerta (id_asignacion, fecha_hora_recepcion);

-- Lo que hace el equipo PRLAC con la alerta. Sin fila = sin asignar.
-- Asumir: INSERT ... ON CONFLICT (id_alerta) DO UPDATE ... WHERE fecha_hora_toma IS NULL
-- AND fecha_hora_cierre IS NULL; si no afecta filas, otra persona ya lo tomó o ya está cerrada.
-- Lo valida el backend: la clasificación solo en alertas clínicas.
CREATE TABLE atencion_alerta (
	id_alerta uuid PRIMARY KEY REFERENCES alerta (id_alerta) ON DELETE CASCADE,
	id_usuario_responsable uuid REFERENCES usuario (id_usuario),
	fecha_hora_toma timestamptz,                -- las reasignaciones quedan en la auditoría
	fecha_hora_cierre timestamptz,
	id_usuario_resolutor uuid REFERENCES usuario (id_usuario),  -- vacío si la cerró el sistema
	clasificacion varchar CHECK (clasificacion IN ('POSITIVA', 'FALSA_ALARMA')),
	observaciones_cierre text,                  -- cifrado
	fecha_cierre_seguimiento timestamptz,       -- solo alertas POSITIVA
	CONSTRAINT atencion_no_vacia CHECK (fecha_hora_toma IS NOT NULL OR fecha_hora_cierre IS NOT NULL),
	CONSTRAINT atencion_toma CHECK ((fecha_hora_toma IS NULL) = (id_usuario_responsable IS NULL)),
	CONSTRAINT atencion_cierre CHECK (fecha_hora_cierre IS NOT NULL
		OR (id_usuario_resolutor IS NULL AND clasificacion IS NULL AND observaciones_cierre IS NULL)),
	CONSTRAINT atencion_orden CHECK (fecha_hora_cierre IS NULL OR fecha_hora_toma IS NULL
		OR fecha_hora_cierre >= fecha_hora_toma),
	-- El seguimiento tiene responsable
	CONSTRAINT atencion_positiva CHECK (clasificacion IS DISTINCT FROM 'POSITIVA' OR id_usuario_responsable IS NOT NULL),
	CONSTRAINT atencion_seguimiento CHECK (fecha_cierre_seguimiento IS NULL
		OR (clasificacion = 'POSITIVA' AND fecha_cierre_seguimiento >= fecha_hora_cierre))
);

-- Mis casos, en el dashboard
CREATE INDEX atencion_alerta_responsable ON atencion_alerta (id_usuario_responsable);

-- Cada aviso que el reloj pidió y el servidor envió a un contacto.
-- El estado de entrega es la fecha más avanzada (fallo > lectura > entrega > envío).
-- Lo valida el backend: el vínculo es del paciente de la alerta; la persona tiene el canal pedido
-- (y, en WhatsApp, opt-in vigente); la alerta no está cancelada.
-- La clave hacia contacto_paciente es diferida: permite borrar al paciente completo,
-- pero no un vínculo suelto que tiene intentos.
CREATE TABLE registro_intento (
	id_intento uuid PRIMARY KEY DEFAULT gen_random_uuid(),
	event_id uuid NOT NULL UNIQUE,              -- si el reloj reintenta, no se envía dos veces (2.10.2)
	id_alerta uuid NOT NULL REFERENCES alerta (id_alerta) ON DELETE CASCADE,
	id_contacto_paciente uuid NOT NULL
		REFERENCES contacto_paciente (id_contacto_paciente) DEFERRABLE INITIALLY DEFERRED,
	canal varchar NOT NULL CHECK (canal IN ('WHATSAPP', 'CORREO')),
	ronda int NOT NULL,
	id_externo varchar UNIQUE,                  -- ID del mensaje en Meta o en el correo
	fecha_hora_envio timestamptz,
	fecha_hora_entrega timestamptz,
	fecha_hora_lectura timestamptz,             -- solo WhatsApp
	fecha_hora_fallo timestamptz,
	motivo_fallo varchar,
	respuesta varchar CHECK (respuesta IN ('VOY_EN_CAMINO', 'NO_PUEDO')),
	fecha_hora_respuesta timestamptz,
	-- Un aviso por contacto, canal y ronda, aunque el reloj genere otro event_id (ej. tras reiniciarse)
	UNIQUE (id_alerta, id_contacto_paciente, canal, ronda),
	CONSTRAINT intento_ronda CHECK (ronda IN (1, 2)),
	CONSTRAINT intento_respuesta CHECK ((respuesta IS NULL) = (fecha_hora_respuesta IS NULL)),
	CONSTRAINT intento_fallo CHECK (motivo_fallo IS NULL OR fecha_hora_fallo IS NOT NULL),
	CONSTRAINT intento_lectura CHECK (fecha_hora_lectura IS NULL OR canal = 'WHATSAPP')
);

-- Lo revisa la clave diferida al borrar vínculos
CREATE INDEX registro_intento_contacto_paciente ON registro_intento (id_contacto_paciente);

-- Avisos al reloj sobre una alerta (2.3). Uno de cada tipo; los reintentos suman en intentos.
CREATE TABLE aviso_fcm (
	id_aviso uuid PRIMARY KEY DEFAULT gen_random_uuid(),
	id_alerta uuid NOT NULL REFERENCES alerta (id_alerta) ON DELETE CASCADE,
	tipo varchar NOT NULL CHECK (tipo IN ('ALERTA_CONFIRMADA', 'ALERTA_RESUELTA', 'SIMULACRO')),
	fecha_hora_envio timestamptz,
	fecha_hora_recepcion timestamptz,           -- la informa el reloj
	intentos int NOT NULL DEFAULT 0,
	UNIQUE (id_alerta, tipo),
	CONSTRAINT aviso_fcm_intentos CHECK (intentos >= 0)
);

CREATE TABLE destino_derivacion (
	codigo varchar PRIMARY KEY,
	nombre varchar NOT NULL,
	activo boolean NOT NULL DEFAULT true
);

-- Notas y acciones del equipo sobre un caso. "Derivada" se ve aquí (tipo DERIVACION), no es un estado.
-- Lo valida el backend: no se agrega seguimiento después de atencion_alerta.fecha_cierre_seguimiento.
CREATE TABLE seguimiento (
	id_seguimiento uuid PRIMARY KEY DEFAULT gen_random_uuid(),
	id_alerta uuid NOT NULL REFERENCES alerta (id_alerta) ON DELETE CASCADE,
	id_usuario uuid NOT NULL REFERENCES usuario (id_usuario),
	tipo varchar NOT NULL CHECK (tipo IN ('LLAMADA', 'VISITA', 'DERIVACION', 'NOTA')),
	codigo_destino varchar REFERENCES destino_derivacion (codigo),
	nota text,                                  -- cifrado
	fecha_hora timestamptz NOT NULL,
	CONSTRAINT seguimiento_destino CHECK ((tipo = 'DERIVACION') = (codigo_destino IS NOT NULL))
);

-- Historial del caso, en orden
CREATE INDEX seguimiento_alerta ON seguimiento (id_alerta, fecha_hora);

-- Estado calculado de cada alerta: lo que hace el reloj (contacto) y lo que hace el equipo (atención)
CREATE VIEW alerta_estado AS
SELECT a.id_alerta,
	CASE
		WHEN a.fecha_hora_cancelacion IS NOT NULL THEN 'CANCELADA'
		WHEN t.fecha_hora_cierre IS NOT NULL THEN 'RESUELTA'
		WHEN EXISTS (SELECT 1 FROM registro_intento i
			WHERE i.id_alerta = a.id_alerta AND i.respuesta = 'VOY_EN_CAMINO') THEN 'CONFIRMADA'
		WHEN a.fecha_hora_sin_respuesta IS NOT NULL THEN 'SIN_RESPUESTA'
		WHEN EXISTS (SELECT 1 FROM registro_intento i WHERE i.id_alerta = a.id_alerta) THEN 'AVISANDO_CONTACTO'
		WHEN a.espera_dia_habil THEN 'PENDIENTE_DIA_HABIL'
		ELSE 'RECIBIDA'
	END AS estado_contacto,
	CASE
		WHEN t.clasificacion = 'POSITIVA' AND t.fecha_cierre_seguimiento IS NULL THEN 'EN_SEGUIMIENTO'
		WHEN t.fecha_hora_cierre IS NOT NULL THEN 'RESUELTA'
		WHEN t.fecha_hora_toma IS NOT NULL THEN 'EN_ATENCION'
		ELSE 'SIN_ASIGNAR'
	END AS estado_atencion,
	CASE WHEN a.fecha_hora_agravamiento IS NOT NULL THEN 'GRAVE' ELSE a.severidad END AS severidad_actual
FROM alerta a
LEFT JOIN atencion_alerta t USING (id_alerta);
